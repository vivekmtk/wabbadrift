"""Builders for small synthetic MO2 instances and .wabbajack files used by the tests."""

from __future__ import annotations

import json
import uuid
import zipfile
from pathlib import Path

from wabbadrift.hashing import hash_bytes

GEN_HEADER = "# This file was automatically generated by Mod Organizer."


def qt_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def write_mo2_ini(
    mo2_dir: Path,
    *,
    game_path: Path,
    profile: str,
    downloads: Path | None = None,
    executables: list[dict] | None = None,
    spaced: bool = False,
    extra: str = "",
) -> Path:
    """Write a ModOrganizer.ini; ``spaced=True`` uses Wabbajack's ``key = value`` style."""
    eq = " = " if spaced else "="
    lines = [
        "[General]",
        f"gameName{eq}Skyrim Special Edition",
        f"selected_profile{eq}@ByteArray({profile})",
        f"gamePath{eq}@ByteArray({qt_escape(str(game_path))})",
        "",
        "[customExecutables]",
    ]
    exes = executables or []
    lines.append(f"size{eq}{len(exes)}")
    for i, exe in enumerate(exes, 1):
        for key in ("arguments", "binary", "title", "workingDirectory"):
            value = exe.get(key, "")
            if key in ("arguments", "workingDirectory"):
                value = qt_escape(value)
            lines.append(f"{i}\\{key}{eq}{value}")
    lines += ["", "[Settings]"]
    if downloads:
        lines.append(f"download_directory{eq}{downloads.as_posix()}")
    if extra:
        lines += ["", extra]
    path = mo2_dir / "ModOrganizer.ini"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def write_files(root: Path, files: dict[str, bytes | str]) -> None:
    for rel, data in files.items():
        p = root / rel.replace("\\", "/")
        p.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(data, str):
            data = data.encode("utf-8")
        p.write_bytes(data)


def write_profile(
    profile_dir: Path,
    *,
    modlist: list[str],
    plugins: list[str] | None = None,
    loadorder: list[str] | None = None,
    plugingroups: dict[str, str] | None = None,
    settings: str = "[General]\nLocalSettings=true\n",
    header: bool = True,
    extra_files: dict[str, str] | None = None,
) -> None:
    """``modlist`` is in file order, highest priority first: ``["+ModA", "-S_separator"]``."""
    profile_dir.mkdir(parents=True, exist_ok=True)

    def put(name: str, lines: list[str]) -> None:
        body = ([GEN_HEADER] if header else []) + lines
        (profile_dir / name).write_text("\n".join(body) + "\n", encoding="utf-8")

    put("modlist.txt", modlist)
    put("plugins.txt", plugins or [])
    put("loadorder.txt", loadorder or [])
    if plugingroups is not None:
        put("plugingroups.txt", [f"{k}|{v}" for k, v in plugingroups.items()])
    (profile_dir / "settings.ini").write_text(settings, encoding="utf-8")
    write_files(profile_dir, extra_files or {})


class WabbajackBuilder:
    """Collects archives and directives, then writes a .wabbajack zip."""

    def __init__(
        self, name: str = "Synth", version: str = "1.0.0", game="SkyrimSpecialEdition"
    ):
        self.data = {
            "Name": name,
            "Version": version,
            "Author": "test",
            "GameType": game,
            "WabbajackVersion": "2.2.2.0",
            "Website": "",
            "Readme": "",
            "Description": "",
            "Image": "",
            "OtherGames": [],
            "IsNSFW": False,
            "Archives": [],
            "Directives": [],
        }
        self.inline: dict[str, bytes] = {}

    def nexus_archive(
        self, name: str, mod_id: int, file_id: int, version="1.0", size=1234
    ) -> str:
        ahash = hash_bytes(f"archive:{name}".encode())
        self.data["Archives"].append(
            {
                "Hash": ahash,
                "Name": name,
                "Size": size,
                "Meta": f"[General]\nmodID={mod_id}\nfileID={file_id}",
                "State": {
                    "$type": "NexusDownloader, Wabbajack.Lib",
                    "ModID": mod_id,
                    "FileID": file_id,
                    "Version": version,
                    "Name": name.rsplit(".", 1)[0],
                    "Author": "someone",
                },
            }
        )
        return ahash

    def from_archive(
        self, to: str, data: bytes | str, archive: str, inner: str
    ) -> None:
        data = data.encode() if isinstance(data, str) else data
        self.data["Directives"].append(
            {
                "$type": "FromArchive",
                "ArchiveHashPath": [archive, inner],
                "Hash": hash_bytes(data),
                "Size": len(data),
                "To": to,
            }
        )

    def inline_file(self, to: str, data: bytes | str, remapped: bool = False) -> None:
        data = data.encode() if isinstance(data, str) else data
        sid = str(uuid.uuid4())
        self.inline[sid] = data
        self.data["Directives"].append(
            {
                "$type": "RemappedInlineFile" if remapped else "InlineFile",
                "Hash": hash_bytes(data),
                "Size": len(data),
                "SourceDataID": sid,
                "To": to,
            }
        )

    def write(self, path: Path) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
            z.writestr("modlist", json.dumps(self.data))
            for sid, data in self.inline.items():
                z.writestr(sid, data)
        return path
